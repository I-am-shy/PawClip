// ── 内容类型（kind）─────────────────────────────────────────────

// 与 DESIGN.md §4.1 的 items.kind 取值一致。
const (
	KindText  = "text"
	KindHTML  = "html"
	KindRTF   = "rtf"
	KindImage = "image"
	KindFiles = "files"
	KindMixed = "mixed"
)

// PreviewMaxChars 是列表摘要的截断长度（DESIGN.md §4.1：preview 截断 200 字符）。
const PreviewMaxChars = 200

// TextMaxCharsDefault 对应设置项 capture.textMaxChars 的默认值（保留前 256K 字符）。
const TextMaxCharsDefault = 262144

// ── 原始类型名 → 角色归并 ────────────────────────────────────────
//
// macOS 给的是 UTI（public.utf8-plain-text …），Windows 给的是格式名或
// CF_* 常量名。归并到同一组 Role 之后，filter 与 normalize 就能完全平台无关。
//
// Windows 侧的约定：保密标记类格式只有在其值"确实触发排除"时才写进
// Raw.RawTypes（见 windows.go），因此这里的判定可以退化为纯名字查表。

// Role 是一个剪贴板表示在语义上的类别。
type Role string

const (
	RoleText    Role = "text"
	RoleHTML    Role = "html"
	RoleRTF     Role = "rtf"
	RoleImage   Role = "image"
	RoleFiles   Role = "files"
	RolePrivate Role = "private"
	RoleUnknown Role = "unknown"
)

